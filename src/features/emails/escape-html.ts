/**
 * Escapes HTML special characters to prevent XSS/HTML injection in emails.
 * Same as escapeHtml in the edge functions.
 */
export function escapeHtml(unsafe: string): string {
  return unsafe
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#039;');
}
